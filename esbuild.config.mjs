import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";
import { copyFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/MinestarUA/Obsidian-plugin-FTBQ
Copyright (c) 2026 ProstoMaslo. Licensed under the MIT License.
*/
`;

const prod = process.argv[2] === "production";
// Default: main.js next to manifest.json (standard Obsidian layout, used by the release workflow).
// Set OBSIDIAN_PLUGIN_DIR=<vault>/.obsidian/plugins/ftbquests-editor to build straight into a vault.
const outdir = resolve(process.env.OBSIDIAN_PLUGIN_DIR ?? ".");
mkdirSync(outdir, { recursive: true });

const copyStatic = {
	name: "copy-static",
	setup(build) {
		build.onEnd(() => {
			if (outdir === resolve(".")) return;
			for (const f of ["manifest.json", "styles.css"]) copyFileSync(f, `${outdir}/${f}`);
		});
	},
};

const ctx = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtinModules, ...builtinModules.map((m) => `node:${m}`)],
	format: "cjs",
	target: "es2022",
	platform: "node",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
	outfile: `${outdir}/main.js`,
	plugins: [copyStatic],
});

if (prod) {
	await ctx.rebuild();
	await ctx.dispose();
} else {
	await ctx.watch();
}
